# tipos int e float
#int -> numero inteiro
# o tipo int é usado para representar números inteiros, ou seja, números sem parte decimal. Exemplos de números inteiros incluem -3, 0, 7, 42.
# positivos, negativos e zero são todos representados como inteiros. Em Python, você pode criar um número inteiro simplesmente digitando o número sem ponto decimal. Por exemplo:
print (11) # int positivo 
print (-5) # int negativo
print (0) # int zero

#float -> numero com ponto flutuante
# O tipo float é usado para representar números com parte decimal, ou seja, números que podem ter uma fração. Exemplos de números de ponto flutuante incluem 3.14, -0.001, 2.0.
# float sem sinal é considerado positivo, enquanto float com sinal negativo é considerado negativo. Em Python, você pode criar um número de ponto flutuante digitando o número com um ponto decimal.
print (3.14) # float positivo
print (-0.001) # float negativo
print (2.0) # float zero    

# a função type() pode ser usada para verificar o tipo de uma variável ou valor em Python. Por exemplo:
print(type(11)) # <class 'int'>
print(type(-5)) # <class 'int'> 
print(type(0)) # <class 'int'>
print (type(3.14)) # <class 'float'>    
print (type(-0.001)) # <class 'float'>
print (type(2.0)) # <class 'float'>
print (type(0.0)) # <class 'float'>
print (type (lucas)) # <class 'str'>, pois lucas é uma string
