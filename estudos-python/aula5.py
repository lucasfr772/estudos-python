 # tipo de dado bool ( boolean)
# ao questionar algo em um programa
# só existem duas respostas possiveis: verdadeiro ou falso
# sim (true) ou não (false).
# existem varios operadores para "questionar"
# dentre eles 0 ==, que é um operador lógico que
# questiona se um valor é igual ao outro
print(10 == 10) # Sim => True (verdadeiro) 
print(10 == 11) # Não => False (falso)
print(type(10 == 10)) # <class 'bool'>
print(type(10 == 11)) # <class 'bool'>
print(type(True)) # <class 'bool'>
print(type(False)) # <class 'bool'>
